# برنامج كامل: حساب درجات فصل
def تقدير(درجة):
    if درجة >= 90:
        return "ممتاز"
    elif درجة >= 50:
        return "ناجح"
    else:
        return "راسب"
درجات = {"محمود": 85, "سارة": 92, "علي": 40}
for اسم in درجات:
    print(اسم + ": " + تقدير(درجات[اسم]))
print("المتوسط:")
print(sum(درجات.values()) / len(درجات))
print("أعلى درجة:")
print(max(درجات.values()))

