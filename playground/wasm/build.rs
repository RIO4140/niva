//! سكربت بناء حزمة ملعب WASM (الاجتماع 71 §86 — المرحلة 3: فخ عمق WASM).
//!
//! يرفع مكدس WASM إلى 16MB على `wasm32` وحده، في الحزمة نفسها —
//! فكل بناء (محلي بـ wasm-pack أو CI) ينال المكدس نفسه، بلا
//! اعتماد على متغير بيئة `RUSTFLAGS` (الذي لا يراه البناء
//! المحلي، وكان سبب الفخ: الحزمة المبنية محليا نالت المكدس
//! الافتراضي 1MB فانهار التكرار العميق عند N=250، بل والشكل
//! الأقصى عند N=100 — دون الحد 1000 بكثير، فلم تطلق رسالة
//! الخطأ العربية أبدا). بالقياس القديم (الاجتماع 17، بمكدس
//! 16MB): الشكل الأقصى يكمل إلى N=1500 ويفشل عند 1531، فالحد
//! 1000 يثبت بهامش ~33% متى كان المكدس 16MB. بلا أثر على
//! الأصلي، وبلا اعتماد جديد، وبلا بايثون.
//! `RUSTFLAGS` في CI Pages يحمل القيمة نفسها — تكرار حميد.

fn main() {
    let target = std::env::var("TARGET").unwrap_or_default();
    if target == "wasm32-unknown-unknown" {
        println!("cargo:rustc-link-arg=-zstack-size=16777216");
    }
}
