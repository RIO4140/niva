//! أسماء الأوامر وطبقاتها (الدفعة 3 — التشغيل، الاجتماع
//! 57 §72، الميزتان 28 و44): ترتيب طبقات البحث عن
//! الأمر في نيفا، ووصف أمر باسمه.
//!
//! الترتيب (الأول يفوز): أمر طرفي → اختصار → كلمة
//! محجوزة → دالة معرفة → دالة مدمجة → أداة → غير
//! موجود. والعبارة الطرفية التي تمرر إلى دالة مدمجة
//! (`انتقل`، `ادفع مجلد`، `ابحث في ملف`، `حول إلى
//! عدد`) تُصنف دالتها لا العبارة — فالعبارة اسم
//! سطح لا طبقة.
//!
//! التطبيع: الطبقات الطرفية والمحجوزة تُقارن بعد
//! تطبيع الكلمة (`normalize_cli_word`: تجريد
//! التشكيل وتوحيد الهمزات والتاء المربوطة والألف
//! المقصورة) كما يطابق التفاعلي والمحلل نفسهما؛
//! أما الدوال (المعرفة والمدمجة) والأدوات فتُقارن
//! بالتهجئة الأصلية حرفيا كما يفعل استدعاء اللغة
//! نفسه (المعرّفات لا تُطبَّع).

use crate::files::ToolLookup;

/// أمر طرفي (موجود في التفاعلي وحده، لا يُستدعى من
/// الكود) — بالصيغة المطبَّعة. `:خروج` و`خروج`
/// صيغتان لأمر واحد؛ و`تن` في نص المساعدة (التطبيق
/// يملكها، لا المحرك) لكنها أمر طرفي لا كود.
const REPL_COMMANDS: &[&str] = &[
    "شغل",
    "استبدل",
    "تثبيت",
    "تن",
    "معلومات",
    "اعد-الاعدادات",
    "اعد-الضبط",
    "خروج",
    "عكس",
    ":مساعده",
    ":اعرض",
    ":امسح-المحفوظات",
    ":مسح",
    ":اسمح-بالشبكه",
    ":اسمح-بالخادم",
    ":تنزيلات",
    ":خروج",
    "ارجع للبيت",
    "كرر الاخير",
    "امسح الجلسه",
];

/// عبارة طرفية كاملة تمرر إلى دالة مدمجة (بالصيغة
/// المطبَّعة) — تُصنف دالتها في الطبقة الخامسة.
const PHRASE_BUILTINS: &[(&str, &str)] = &[
    ("ادفع مجلد", "ادفع_مجلد"),
    ("اخرج مجلد", "أخرج_مجلد"),
    ("اعرض المكدس", "اعرض_المكدس"),
    ("امسح المكدس", "امسح_المكدس"),
    ("ابحث في ملف", "ابحث_في_ملف"),
    ("ابحث عن ملف", "ابحث_عن"),
    ("حول الي عدد", "عدد"),
    ("انتقل", "انتقل"),
    ("انسخ", "انسخ"),
    ("انقل", "انقل"),
    ("موجود", "موجود"),
];

/// طبّع استعلاما (كلمة أو عبارة) كلمة كلمة، كما
/// يطابق التفاعلي الكلمة الأولى بعد التطبيع.
fn normalize_query(name: &str) -> String {
    name.split_whitespace()
        .map(crate::lexer::normalize_cli_word)
        .collect::<Vec<_>>()
        .join(" ")
}

/// هل هذا الاسم (بعد التطبيع) أمر طرفي؟
pub(crate) fn is_repl_command_name(name: &str) -> bool {
    REPL_COMMANDS.contains(&normalize_query(name).as_str())
}

/// الدالة المدمجة التي تمرر إليها هذه العبارة
/// الطرفية (بعد التطبيع)، إن كانت عبارة معروفة.
pub(crate) fn phrase_builtin(name: &str) -> Option<&'static str> {
    let norm = normalize_query(name);
    PHRASE_BUILTINS
        .iter()
        .find(|(phrase, _)| *phrase == norm)
        .map(|(_, builtin)| *builtin)
}

/// صف أمرا باسمه بترتيب الطبقات (الميزة 44).
/// `is_user_function` يفحص التعريف في نطاق المتصل
/// (بالتهجئة الأصلية حرفيا)؛ و`locate_tool` يبحث
/// ملف الأداة باسمه الكامل (مع الامتداد) ويعيد
/// نتيجة البحث (الميزة 39).
pub fn describe_command(
    name: &str,
    is_user_function: impl Fn(&str) -> bool,
    locate_tool: impl Fn(&str) -> ToolLookup,
) -> &'static str {
    let norm = normalize_query(name);
    if REPL_COMMANDS.contains(&norm.as_str()) {
        return "امر طرفي";
    }
    if !norm.contains(' ') && crate::repl::is_shortcut_code(&norm) {
        return "اختصار";
    }
    if !norm.contains(' ') && crate::lexer::is_keyword_word(&norm) {
        return "كلمة محجوزة";
    }
    if is_user_function(name) {
        return "دالة معرفة";
    }
    if crate::semantic::is_builtin(name)
        || phrase_builtin(name).is_some()
    {
        return "دالة مدمجة";
    }
    // الاسم الحاوي مسارا لا يُبحث في القرص إطلاقا
    // (كـ`شغل` تماما) — فلا يصنَّف ملف خارج النطاق
    // أداة أبدا.
    if name.contains('/') || name.contains('\\') || name.contains("..") {
        return "غير موجود";
    }
    let file_name = if name.ends_with(".نيفا") {
        name.to_string()
    } else {
        format!("{}.نيفا", name)
    };
    match locate_tool(&file_name) {
        ToolLookup::Found { in_home, .. } => {
            if in_home {
                "اداة في ~"
            } else {
                "اداة في $نيفا"
            }
        }
        _ => "غير موجود",
    }
}
